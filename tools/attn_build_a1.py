"""Write the two files for backlog A1 (bounded-shift softmax) from submission.py and attn_ws.cu,
leaving submission.py itself as submitted:

  muse_attention_decode/submission_a1.py
      submission.py with attn_ws.cu inlined and every attn_ws route that runs var 16 (sliding
      verify at any batch, full verify above batch 2) running var A1_VAR instead.
  muse_attention_decode/bench.py
      submission.py with attn_ws.cu inlined (routing unchanged: var 16), plus the
      tools/attn_make_bench_ws.py sweep without its GATHER part, over VARIANTS, and phase
      stamps (mode 2) of var 16 and of each A1 variant on every q_len 8 shape.

    python3 tools/attn_build_a1.py
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import attn_make_bench  # noqa: E402
import attn_make_bench_ws  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "muse_attention_decode"
A1_VAR = 272
VARIANTS = ["_ref32", "_fused_prep", "_ws@x=0", "_ws@x=16", "_ws@x=16,m=1", "_ws@x=144",
            "_ws@x=272"]
STAMP_VARS = [16, 144, 272]


def sub(text, old, new, count=1):
    if text.count(old) != count:
        raise SystemExit(f"expected {count} of {old!r}, found {text.count(old)}")
    return text.replace(old, new)


def inlined():
    src = (DIR / "submission.py").read_text()
    cu = (DIR / "attn_ws.cu").read_text()
    new, n = re.subn(r'_WS_SRC = r""".*?"""', lambda _: f'_WS_SRC = r"""\n{cu}"""', src,
                     flags=re.S)
    if n != 1:
        raise SystemExit("no _WS_SRC block in submission.py")
    return new


def write_submission(base):
    text = sub(base, """_WS_VAR = {
    ("sliding", 1): 16, ("sliding", 16): 16, ("sliding", 32): 16,
    ("full", 1): None, ("full", 16): 16, ("full", 32): 16,
}""", f"""_WS_VAR = {{
    ("sliding", 1): {A1_VAR}, ("sliding", 16): {A1_VAR}, ("sliding", 32): {A1_VAR},
    ("full", 1): None, ("full", 16): {A1_VAR}, ("full", 32): {A1_VAR},
}}""")
    text = sub(text, """    if window:
        return 16
    return 16 if cfg["batch"] > 2 else None""", f"""    if window:
        return {A1_VAR}
    return {A1_VAR} if cfg["batch"] > 2 else None""")
    text = sub(text, """# on full-context verify b16/b32 in bench a8a4666a91d54d68.
""", f"""# on full-context verify b16/b32 in bench a8a4666a91d54d68.
# Var {A1_VAR} is var 16 with backlog A1's bounded-shift softmax at tau 8: a row's shift moves
# only when a tile's max passes it by more than 8 (log2 units), so O is rescaled less often;
# P stays at most 2^8 in f16 (tools/attn_emulate_a1.py, docs/runs-attention.md).
""")
    text = sub(text, 'name="okc_attn_ws_v2"', 'name="okc_attn_ws_a1"')
    text = sub(text, "softmax as FA3's, and f16 P.V into FP32 on wgmma, and four loader warps\n",
               "softmax as FA3's but with a bounded shift (backlog A1, tau 8), f16 P.V into\n"
               "      FP32 on wgmma, and four loader warps\n")
    (DIR / "submission_a1.py").write_text(text)


def write_bench(base):
    helpers = attn_make_bench.HARNESS.format(variants=[], stamps=[])
    helpers = helpers.split("\nimport os as _os\n")[0]
    runner = attn_make_bench_ws.RUNNER.format(
        variants=VARIANTS, gather_src=attn_make_bench_ws.GATHER_SRC,
        gather_cpp=attn_make_bench_ws.GATHER_CPP, gather=False)
    runner = sub(runner, "def _ws_stamps(data, cfg_splits):",
                 "def _ws_stamps(data, cfg_splits, var=16):")
    runner = sub(runner, "_ws(data, splits=cfg_splits, mode=2, dbg=dbg)",
                 "_ws(data, splits=cfg_splits, mode=2, var=var, dbg=dbg)")
    runner = sub(runner, """            try:
                print(f"STAMPS b={batch:2d} {layer:7s} L={q_len} " + _ws_stamps(data, None),
                      flush=True)
            except Exception as exc:
                print(f"STAMPS failed: {type(exc).__name__}: {exc}", flush=True)""",
                 f"""            for var in {STAMP_VARS!r}:
                try:
                    print(f"STAMPS b={{batch:2d}} {{layer:7s}} L={{q_len}} x={{var}} "
                          + _ws_stamps(data, None, var), flush=True)
                except Exception as exc:
                    print(f"STAMPS x={{var}} failed: {{type(exc).__name__}}: {{exc}}",
                          flush=True)""")
    runner = sub(runner, "# Generated by tools/attn_make_bench_ws.py.",
                 "# Generated by tools/attn_build_a1.py (tools/attn_make_bench_ws.py's runner).")
    (DIR / "bench.py").write_text(base + helpers + runner)


def main():
    base = inlined()
    write_submission(base)
    write_bench(base)
    print(f"wrote submission_a1.py (var {A1_VAR}) and bench.py with {VARIANTS}, "
          f"stamps {STAMP_VARS}")


if __name__ == "__main__":
    main()
