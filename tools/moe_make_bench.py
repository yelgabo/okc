"""Write muse_moe_w4a16/bench.py: submission.py plus a measurement pass inside prepare().

prepare() runs untimed for up to 300 s and its prints come back in the run log, so one
`okc check muse_moe_w4a16/bench.py` measures, with a cold L2 before every graph replay:
- STREAM: achieved HBM read bandwidth of a plain vectorized read kernel over buffer sizes;
- ROUTE: per scored shape and routing seed, the local experts touched, routes, the largest
  expert's tokens, and unique weight bytes;
- SPLIT: Marlin GEMM1, silu_and_mul, Marlin GEMM2 and the finalizer timed on their own, and
  the whole forward, with achieved bandwidth over the unique weight bytes.
Usage: python3 tools/moe_make_bench.py [extra_bench_file]
"""

