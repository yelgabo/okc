def pub_patch(text):
    for old, new in PUB_PATCHES:
        if text.count(old) != 1:
            raise SystemExit(f"public patch does not apply: {old[:80]!r}")
        text = text.replace(old, new)
    if "threading" in text:
        raise SystemExit("the public file still names threading")
    return text


def main():
    args = sys.argv[1:]
    opts = {"seeds": 2, "rounds": 12, "deadline": 265}
    pos = []
    for a in args:
        if a.startswith("--"):
            k, _, v = a[2:].partition("=")
            opts[k] = int(v)
        else:
            pos.append(a)
    if len(pos) != 2:
        raise SystemExit(__doc__)
    out, pub = Path(pos[0]), Path(pos[1])
    pub_src = pub_patch(pub.read_text())
    src = (ROOT / "muse_decode_layer/submission.py").read_text()
    out.write_text(src + AB.format(pub_src=pub_src, seeds=opts["seeds"], rounds=opts["rounds"],
                                   deadline=opts["deadline"]))
    print(f"wrote {out}: public {pub} ({len(pub_src)} chars), seeds {opts['seeds']}, "
          f"rounds {opts['rounds']}")


if __name__ == "__main__":
    main()
