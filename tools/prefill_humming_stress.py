"""Append prepare-time M32 fresh-input Humming routing/replay checks; diagnostic only.

Input is generated by prefill_humming_indexed.py. Output never goes on the board.
Official plain-candidate tests supply independent mathematical correctness; this
checks state freshness and device metadata, using matched eager numerical envelope.
"""
from pathlib import Path
import sys

STRESS = r'''

_hi_plain_prepare = prepare
def prepare(weights):
    state=_hi_plain_prepare(weights)
    dev=weights["w13"].device
    gen=torch.Generator(device=dev).manual_seed(202611012)
    banks=[]
    for b in range(4):
        x=torch.randn((32,4096),generator=gen,device=dev,dtype=torch.bfloat16)
        ids=torch.arange(32,40,device=dev,dtype=torch.int32).expand(32,8).clone()
        if b==1: ids[:,0]=0
        if b==2: ids=torch.arange(8,device=dev,dtype=torch.int32).expand(32,8).clone()
        if b==3:
            ids[:,0]=31
            ids[::2,1]=7
        tw=torch.rand((32,8),generator=gen,device=dev)
        tw=tw/tw.sum(-1,keepdim=True)
        ref=_experts(x,tw,ids,state).clone()
        valid=(ids>=0)&(ids<32)
        expected=(torch.nn.functional.one_hot(ids.clamp(0,31).long(),32)
                  *valid.unsqueeze(-1)).sum((0,1)).to(torch.int32)
        banks.append((x,ids,tw,ref,expected))
    xb,ib,tb=(banks[0][i].clone() for i in range(3))
    ws=state["hum"]["workspace"][32]

    def stats(out,ref):
        delta=out.float()-ref.float()
        rel=delta.square().sum().sqrt()/ref.float().square().sum().sqrt().clamp(min=1e-30)
        row=(delta.abs().amax(-1)/ref.float().abs().amax(-1).clamp(min=1e-30)).amax()
        finite=(~torch.isfinite(out)).any().float()
        return torch.stack((rel,row,finite))

    ctrl=torch.zeros(3,device=dev)
    cshare=torch.zeros((),device=dev)
    # Matched eager-control envelope, never a changed official output tolerance.
    for i in range(64):
        x,ids,tw,ref,_=banks[i%4]
        st=stats(_experts(x,tw,ids,state),ref)
        ctrl=torch.maximum(ctrl,st)
        cshare+=(st[0]>1e-4).float()
    graph=torch.cuda.CUDAGraph()
    with torch.cuda.graph(graph):
        out=_experts(xb,tb,ib,state)
    peak=torch.zeros(3,device=dev)
    share=torch.zeros((),device=dev)
    invalid=torch.zeros((),device=dev)
    zero_error=torch.zeros((),device=dev)
    for i in range(2000):
        x,ids,tw,ref,expected=banks[i%4]
        xb.copy_(x); ib.copy_(ids); tb.copy_(tw)
        graph.replay()
        st=stats(out,ref)
        peak=torch.maximum(peak,st)
        share+=(st[0]>1e-4).float()
        invalid=torch.maximum(invalid,(ws["counts"]!=expected).any().float())
        for meta in ws["meta"]:
            want=(torch.div(expected+meta["bm"]-1,meta["bm"],rounding_mode="floor")*meta["bm"]).sum()
            invalid=torch.maximum(invalid,(meta["np"][0]!=want).float())
        if i%4==0:
            zero_error=torch.maximum(zero_error,out.abs().amax().float())
    vals=torch.cat((ctrl,peak,cshare.reshape(1)/64,share.reshape(1)/2000,
                    invalid.reshape(1),zero_error.reshape(1))).cpu().tolist()
    print("HUMFRESH M32 replays2000 control64 [ctrl_rel,row,nonfinite,cand_rel,row,nonfinite,ctrl_share,cand_share,bad_metadata,zero_error]",vals,flush=True)
    cr,ce,cn,rr,re,rn,cs,rs,bad,zero=vals
    assert cn==0 and rn==0 and bad==0 and zero==0, "Humming fresh nonfinite/metadata/zero-local failure"
    assert rr<1e-2 and rr<=max(1e-4,2*cr), "Humming fresh relative error exceeds eager envelope"
    assert re<=max(2**-7,2*ce) and rs<=2*cs+2/2000, "Humming fresh row/share exceeds eager envelope"
    return state
'''

if __name__=='__main__':
    Path(sys.argv[2]).write_text(Path(sys.argv[1]).read_text()+STRESS)
