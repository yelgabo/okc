"""Write a bench file: muse_bf16_proj/submission.py plus a timing sweep of cproj_kernel variants.

prepare() runs untimed and its prints come back in the run log, so one `okc check <out>` times
every variant below with a cold L2 (CUDA graph replays, flush outside the timed window), next
to the uncompressed proj kernel and cuBLAS. The judge's timing of kernel_fn is unchanged.

    python3 tools/compress_make_bench.py <out.py>
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# (accs, exc_select, nodecode, exc, stages). NODECODE and EXC = false give wrong results; they
# time the decode and the escaped-tile handling (and its shared memory).
VARIANTS = [(2, "true", "false", "true", 4), (1, "true", "false", "true", 4),
            (2, "true", "false", "false", 4)]


def main(out):
    cases = "\n".join(
        f"        case {i}: cproj_launch<S, false, {a}, {e}, {nd}, {ex}, {st}>"
        f"(wc, desc, exc, base4, xp, op, nullptr, m, n, k, stream); break;"
        for i, (a, e, nd, ex, st) in enumerate(VARIANTS))
    occ_cases = "\n".join(
        f"        case {i}: return max_clusters(cproj_kernel<CWARPS, S, false, {a}, {e}, {nd}, "
        f"{ex}, {st}>, n / (CWARPS * 16), S, CWARPS * 32, cproj_smem_bytes<CWARPS, {ex}, {st}>());"
        for i, (a, e, nd, ex, st) in enumerate(VARIANTS))
    bench_fn = f'''
namespace {{
template <int S>
void cproj_bench_s(int v, const uint4* wc, const unsigned* desc, const uint4* exc,
                   unsigned base4, const __nv_bfloat16* xp, __nv_bfloat16* op, int m, int n,
                   int k, cudaStream_t stream) {{
    switch (v) {{
{cases}
    }}
}}

template <typename K>
int max_clusters(K kernel, int gx, int s, int threads, int smem) {{
    cudaLaunchConfig_t cfg = {{}};
    cfg.gridDim = dim3(gx, s);
    cfg.blockDim = dim3(threads);
    cfg.dynamicSmemBytes = smem;
    int count = -1;
    const cudaError_t err = cudaOccupancyMaxActiveClusters(&count, (const void*)kernel, &cfg);
    return err == cudaSuccess ? count : -1000 - (int)err;
}}

// Variant -1 is the uncompressed proj_small. Call after a launch, which sets the smem limit.
template <int S>
int clusters_s(int v, int n) {{
    switch (v) {{
{occ_cases}
    }}
    return max_clusters(proj_kernel<1, 4, 1, 8, S>, n / 64, S, 128,
                        proj_smem_bytes<1, 4, 1, 8>());
}}
}}  // namespace

int64_t cproj_clusters(int64_t v, int64_t n, int64_t k) {{
    const int s = cproj_splits(n, k);
    if (s == 8) {{
        return clusters_s<8>(v, n);
    }} else if (s == 4) {{
        return clusters_s<4>(v, n);
    }}
    return clusters_s<2>(v, n);
}}

torch::Tensor cproj_bench(torch::Tensor x, torch::Tensor wc, torch::Tensor desc,
                          torch::Tensor exc, int64_t base, int64_t v) {{
    const int m = x.size(0);
    const int k = x.size(1);
    const int n = wc.size(0) * 16;
    cproj_check_shape(n, k);
    auto out = torch::empty({{m, n}}, x.options());
    const auto* wp = reinterpret_cast<const uint4*>(wc.data_ptr());
    const auto* dp = reinterpret_cast<const unsigned*>(desc.data_ptr());
    const auto* ep = reinterpret_cast<const uint4*>(exc.data_ptr());
    const unsigned base4 = static_cast<unsigned>(base) * 0x01010101u;
    const auto* xp = reinterpret_cast<const __nv_bfloat16*>(x.data_ptr<at::BFloat16>());
    auto* op = reinterpret_cast<__nv_bfloat16*>(out.data_ptr<at::BFloat16>());
    auto stream = at::cuda::getCurrentCUDAStream();
    const int s = cproj_splits(n, k);
    if (s == 8) {{
        cproj_bench_s<8>(v, wp, dp, ep, base4, xp, op, m, n, k, stream);
    }} else if (s == 4) {{
        cproj_bench_s<4>(v, wp, dp, ep, base4, xp, op, m, n, k, stream);
    }} else {{
        cproj_bench_s<2>(v, wp, dp, ep, base4, xp, op, m, n, k, stream);
    }}
    return out;
}}
'''
    src = (ROOT / "muse_bf16_proj/submission.py").read_text()
    src += f'''

# Generated by tools/compress_make_bench.py: cproj_kernel variants timed inside prepare().
_CBENCH_SRC = _PROJ_SRC + {bench_fn!r}
_CBENCH_VARIANTS = {VARIANTS!r}


def _cbench_time(fn, flush, iters=30):
    fn()
    graph = torch.cuda.CUDAGraph()
    with torch.cuda.graph(graph):
        fn()
    times = []
    for _ in range(iters):
        flush.zero_()
        start = torch.cuda.Event(enable_timing=True)
        end = torch.cuda.Event(enable_timing=True)
        start.record()
        graph.replay()
        end.record()
        times.append((start, end))
    torch.cuda.synchronize()
    ms = sorted(s.elapsed_time(e) for s, e in times)
    return 1000 * ms[len(ms) // 2]


def _run_cbench(state):
    ext = load_inline(
        name="okc_cproj_bench",
        cpp_sources=_PROJ_CPP_SRC + "torch::Tensor cproj_bench(torch::Tensor x, torch::Tensor wc,"
        " torch::Tensor desc, torch::Tensor exc, int64_t base, int64_t v);"
        "int64_t cproj_clusters(int64_t v, int64_t n, int64_t k);",
        cuda_sources=_CBENCH_SRC,
        functions=["cproj_bench", "cproj_clusters"],
        extra_cuda_cflags=["-O3", "-gencode=arch=compute_90a,code=sm_90a"],
    )
    flush = torch.empty(256 << 20, dtype=torch.uint8, device="cuda")
    for layer in PROJ_LAYERS:
        main, desc, exc, base = state["cproj_packed"][layer]
        n = main.shape[0] * 16
        w = state[layer][:n]
        for m in (1, 8):
            x = torch.randn(m, w.shape[1], device="cuda").to(torch.bfloat16)
            ref = x.double() @ w.double().T
            row = []
            us = _cbench_time(lambda: _bf16_gemm_dispatch_impl(x, w, None), flush)
            row.append(f"cublas {{us:5.1f}}")
            us = _cbench_time(lambda: state["proj_fused"](x, state["proj_packed"][layer], n), flush)
            row.append(f"proj {{us:5.1f}}")
            clusters = [ext.cproj_clusters(-1, n, w.shape[1])]
            for v, (accs, sel, nodecode, use_exc, stages) in enumerate(_CBENCH_VARIANTS):
                out = ext.cproj_bench(x, main, desc, exc, base, v)
                err = ((out.double() - ref).norm() / ref.norm()).item()
                exact = nodecode == "false" and use_exc == "true"
                ok = "ok" if err < 5e-3 else f"err {{err:.1e}}"
                us = _cbench_time(lambda: ext.cproj_bench(x, main, desc, exc, base, v), flush)
                tag = f"{{'exc' if use_exc == 'true' else 'noexc'}}-st{{stages}}"
                row.append(f"{{tag}} {{us:5.1f}} {{ok if exact else '-'}}")
                clusters.append(ext.cproj_clusters(v, n, w.shape[1]))
            print(f"CBENCH {{layer:9s}} m={{m}} " + " | ".join(row))
            print(f"CBENCH {{layer:9s}} m={{m}} max active clusters (proj, variants): {{clusters}}")


_prepare_without_cbench = prepare


def prepare(weights):
    state = _prepare_without_cbench(weights)
    try:
        _run_cbench(state)
    except Exception as exc:
        print(f"CBENCH failed: {{type(exc).__name__}}: {{exc}}")
    return state
'''
    Path(out).write_text(src)
    print(f"wrote {out}: {len(VARIANTS)} variants")


if __name__ == "__main__":
    main(sys.argv[1])
