def _hd_case(batch, length, layer, ctx, seed, page=1):
    """The layer diagnostic's synthetic step (_attn_case in muse_decode_layer): small keys,
    values with a per-dim mean, a shuffled page table, every request at ctx."""
    dev = "cuda"
    gen = torch.Generator(device=dev).manual_seed(seed)
    seq = torch.full((batch,), ctx, dtype=torch.int32, device=dev)
    pages_per = (seq + length + page - 1) // page
    total = int(pages_per.sum())
    max_pages = int(pages_per.max())
    perm = torch.randperm(total + 7, generator=gen, device=dev)[:total].to(torch.int32)
    page_table = torch.full((batch, max_pages), -1, dtype=torch.int32, device=dev)
    at = 0
    for b in range(batch):
        n = int(pages_per[b])
        page_table[b, :n] = perm[at:at + n]
        at += n
    shape = (total + 7, page, 2, 64)
    k_cache = (torch.randn(shape, generator=gen, device=dev) * 0.3).to(FP8)
    v_mean = torch.randn((1, 1, 2, 64), generator=gen, device=dev)
    v_cache = (torch.randn(shape, generator=gen, device=dev) * 0.5 + v_mean).to(FP8)
    steps = torch.arange(length, device=dev)
    positions = (seq.long()[:, None] + steps).reshape(-1)
    rows = page_table.long().repeat_interleave(length, 0)
    rows = rows.gather(1, (positions // page)[:, None])[:, 0] * page + positions % page
    tokens = batch * length
    bank = [(torch.randn((tokens, 2304), generator=gen, device=dev) * 2).to(torch.bfloat16)
            for _ in range(4)]
    scale = torch.tensor(1.0, dtype=torch.float32, device=dev)
    data = {
        "qkv": bank[0], "k_cache": k_cache, "v_cache": v_cache, "positions": positions,
        "cache_loc": rows, "cache_seqlens": seq + length,
        "cu_seqlens_q": torch.arange(0, tokens + 1, length, dtype=torch.int32, device=dev),
        "scheduler_metadata": None, "k_scale": scale, "v_scale": scale.clone(),
        "page_table": page_table, "seq_lens": seq,
        "config": {"batch": batch, "q_len": length, "tokens": tokens, "num_q_heads": 16,
                   "num_kv_heads": 2, "head_dim": 64, "page_size": page,
                   "window": 2048 if layer == "sliding" else 0,
                   "rope_theta": 500000.0 if layer == "sliding" else 0.0,
                   "qk_scale_factor": 5.4730064863875, "sm_scale": 0.125, "kv_scale": 1.0},
    }
    return data, bank


def _hd_rel(a, b):
    return float((a.float() - b.float()).norm() / b.float().norm().clamp(min=1e-12))


def _hd_ulps(a, b):
    """(elements that differ, largest gap in BF16 ulps of the larger magnitude)."""
    a, b = a.float().flatten(), b.float().flatten()
    ne = a != b
    n = int(ne.sum())
    if n == 0:
        return 0, 0.0
    big = torch.maximum(a[ne].abs(), b[ne].abs()).clamp(min=1e-30)
    ulp = torch.exp2(torch.floor(torch.log2(big)) - 7)
    return n, float(((a[ne] - b[ne]).abs() / ulp).max())


_HD_WS = {"calls": 0, "dirty": 0, "first": ""}


def _hd_ws_scan(label):
    """The entry state of the next launch: rows, row sums, tickets and the next parity
    counters zero (the flat cooperative counter by its epoch at [16386])."""
    torch.cuda.synchronize()
    st = _ONE_STATE[torch.device("cuda", torch.cuda.current_device())]
    cnt = st["cnt"]
    acc_nz = int((st["acc"] != 0).sum())
    l_nz = int((st["l"] != 0).sum())
    tickets_nz = int((cnt[:4096] != 0).sum())
    ep = cnt[8192:8192 + 2048].long()
    nxt = 4096 + 2 * torch.arange(2048, device=cnt.device) + (ep & 1)
    coop_nz = int((cnt[nxt] != 0).sum())
    flat_nz = int(cnt[16384 + (int(cnt[16386]) & 1)] != 0)
    other_nz = int((cnt[16387:] != 0).sum())
    _HD_WS["calls"] += 1
    bad = acc_nz + l_nz + tickets_nz + coop_nz + flat_nz + other_nz
    if bad:
        _HD_WS["dirty"] += 1
        if not _HD_WS["first"]:
            _HD_WS["first"] = (f"{label}: rows={acc_nz} l={l_nz} tickets={tickets_nz} "
                               f"coop_next={coop_nz} flat_next={flat_nz} other={other_nz}")
    return bad == 0


def _hd_prod(data, scan=True, label="prod"):
    def run(q):
        out = _one(dict(data, qkv=q)).clone()
        if scan:
            _hd_ws_scan(label)
        return out
    return run


_HD_DETBUF = {}


def _hd_det(data):
    cfg = data["config"]
    batch = cfg["batch"]
    st = _one_state(data["qkv"].device)
    grid = min(_ONE_TARGET, st["resident"].get((1, 49), 0))
    size = batch * grid * 2 * 16 * 68
    if _HD_DETBUF.get("n", 0) < size:
        _HD_DETBUF["buf"] = torch.zeros(size, dtype=torch.int32, device="cuda")
        _HD_DETBUF["n"] = size
    buf = _HD_DETBUF["buf"]

    def run(q):
        return _ONE_DET.attn_one(
            q, data["page_table"], data["seq_lens"], data["cache_loc"],
            _inv_freq(1.0, 64, q.device), data["k_scale"], data["v_scale"], data["k_cache"],
            data["v_cache"], st["acc"], st["l"], st["cnt"], batch, 1, cfg["page_size"], 0,
            False, cfg["sm_scale"] * cfg["qk_scale_factor"] * LOG2E, grid, 1, 49,
            False, buf, 0).clone()
    return run


_HD_FLUSH = None


def _hd_probe(run, bank, run_other=None, flush=False, n=4):
    """The layer's _hist_probe (tools/dl_history_diag.py), plus ulp counts and rep8."""
    def call(fn, q):
        if flush:
            _HD_FLUSH.zero_()
        return fn(q)
    rep = hist = sep = 0.0
    worst = [0, 0.0]
    rep8 = 1
    for k in range(n):
        call(run, bank[k])
        o2 = call(run, bank[k])
        o3 = call(run, bank[k])
        rep = max(rep, _hd_rel(o2, o3))
        outs = [call(run, bank[k]) for _ in range(8)]
        distinct = []
        for o in outs + [o3]:
            if not any(torch.equal(o, d) for d in distinct):
                distinct.append(o)
        rep8 = max(rep8, len(distinct))
        for j in range(n):
            if j == k:
                continue
            call(run, bank[j])
            o = call(run, bank[k])
            hist = max(hist, _hd_rel(o, o3))
            ne, ul = _hd_ulps(o, o3)
            worst = [max(worst[0], ne), max(worst[1], ul)]
            if run_other is not None:
                call(run_other, bank[j])
                o = call(run, bank[k])
                sep = max(sep, _hd_rel(o, o3))
                ne, ul = _hd_ulps(o, o3)
                worst = [max(worst[0], ne), max(worst[1], ul)]
    return rep, hist, sep, rep8, worst


def _hd_addr(run, bank, n=4):
    """Previous call on a fresh copy of input k (same values, another address)."""
    worst = 0.0
    ne_max = 0
    for k in range(n):
        # Held until the loop ends, so the caching allocator cannot hand back one address.
        copies = [bank[k].clone() for _ in range(3)]
        run(bank[k])
        ref = run(bank[k])
        for cp in copies:
            run(cp)
            o = run(bank[k])
            worst = max(worst, _hd_rel(o, ref))
            ne_max = max(ne_max, _hd_ulps(o, ref)[0])
    return worst, ne_max


def _hd_fmt(r):
    rep, hist, sep, rep8, worst = r
    return (f"rep/hist/sep {rep:.0e}/{hist:.0e}/{sep:.0e} rep8_distinct={rep8} "
            f"worst_elems={worst[0]} worst_ulp={worst[1]:.1f}")


def _hd_main():
    global _HD_FLUSH
    if _ONE is None:
        print("HD no attn_one build", flush=True)
        return
    _HD_FLUSH = torch.empty(256 << 20, dtype=torch.uint8, device="cuda")
    dev = torch.device("cuda", torch.cuda.current_device())
    _one_state(dev)
    print(f"HD ws before any launch clean={_hd_ws_scan('init')}", flush=True)
    for batch in (16, 32):
        data, bank = _hd_case(batch, 1, "full", 80000, 9300 + batch)
        other, _ = _hd_case(batch, 1, "full", 80000, 9300 + batch)
        st = _one_state(dev)
        plan = _one_plan(data["config"], data["page_table"].shape[1], st["resident"])
        tag = f"{batch}x1f"
        prod = _hd_prod(data)
        prod_other = _hd_prod(other)
        r = _hd_probe(prod, bank, prod_other)
        print(f"HD prod {tag} plan={plan} {_hd_fmt(r)} t={_hd_time.time() - _HD_T0:.0f}s",
              flush=True)
        a = _hd_addr(prod, bank)
        print(f"HD addr {tag} prev-call-same-values-other-address rel={a[0]:.0e} "
              f"elems={a[1]}", flush=True)
        r = _hd_probe(_hd_prod(data, scan=False), bank, _hd_prod(other, scan=False), flush=True)
        print(f"HD flush {tag} {_hd_fmt(r)}", flush=True)
        if _ONE_DET is not None:
            det = _hd_det(data)
            det_other = _hd_det(other)
            r = _hd_probe(det, bank, det_other)
            print(f"HD det {tag} {_hd_fmt(r)} t={_hd_time.time() - _HD_T0:.0f}s", flush=True)
            r = _hd_probe(det, bank, det_other, flush=True)
            print(f"HD det-flush {tag} {_hd_fmt(r)}", flush=True)
            # Interleaved with production calls: det must not see their state either.
            ref = det(bank[0])
            mx = 0.0
            for k in range(4):
                prod(bank[k])
                det_other(bank[k])
                mx = max(mx, _hd_rel(det(bank[0]), ref))
            _hd_ws_scan("after det")
            worst_rel = 0.0
            worst_u = (0, 0.0)
            for k in range(4):
                d, pr = det(bank[k]), prod(bank[k])
                worst_rel = max(worst_rel, _hd_rel(d, pr))
                u = _hd_ulps(d, pr)
                worst_u = (max(worst_u[0], u[0]), max(worst_u[1], u[1]))
            print(f"HD det_vs_prod {tag} rel={worst_rel:.1e} elems={worst_u[0]}/"
                  f"{batch * 1024} max_ulp={worst_u[1]:.1f} det_after_mixed_calls={mx:.0e}",
                  flush=True)
        del other, prod_other
        if batch == 16:
            # Cross-plan carry: a call on each other plan, then this plan against its own
            # repeat; the scan runs after every call.
            ref = prod(bank[1])
            ref = prod(bank[1])
            worst = 0.0
            for (fb, fl, flay, fctx, fpage) in ((1, 1, "full", 80000, 1),
                                                 (1, 1, "sliding", 6000, 1),
                                                 (32, 1, "sliding", 6000, 1),
                                                 (16, 8, "sliding", 6000, 1),
                                                 (16, 8, "full", 20000, 1),
                                                 (32, 1, "full", 20000, 64),
                                                 (1, 8, "full", 80000, 1)):
                fd, fbank = _hd_case(fb, fl, flay, fctx, 5000 + fb * fl + fctx, fpage)
                fplan = _one_plan(fd["config"], fd["page_table"].shape[1], st["resident"])
                _hd_prod(fd, label=f"xplan {fb}x{fl}{flay[0]} {fplan}")(fbank[2])
                o = prod(bank[1])
                rel = _hd_rel(o, ref)
                worst = max(worst, rel)
                print(f"HD xplan after {fb}x{fl}{flay[0]} plan={fplan}: 16x1f rel={rel:.0e} "
                      f"elems={_hd_ulps(o, ref)[0]}", flush=True)
                del fd, fbank
            print(f"HD xplan worst={worst:.0e}", flush=True)
        del data, bank
        torch.cuda.empty_cache()
    print(f"HD ws scans={_HD_WS['calls']} dirty={_HD_WS['dirty']} first={_HD_WS['first'] or '-'} "
          f"t={_hd_time.time() - _HD_T0:.0f}s", flush=True)


try:
    _hd_main()
except Exception as _exc:
    import traceback as _tb
    print(f"HD error {type(_exc).__name__}: {str(_exc)[:300]}", flush=True)
    print("HD tb " + " | ".join(_tb.format_exc().splitlines()[-6:]), flush=True)
