"""Build the attention input-history diagnostic (not a candidate, never submitted).

    python3 tools/attn_hist_diag.py [OUT]   (default muse_attention_decode/hist_diag.py)

The layer's history test (d93286b5110a4410, tools/dl_history_diag.py) found the attention
output at full context, batch 16 and 32 (flat mode 49) depending on the previous call's input
through shared state (rep 0, hist = sep = 3e-5 / 8e-5). This file decides between FP32 merge
order (the reds reach L2 in an order that depends on timing) and a carry (state left behind
or read before it is published). At import, on decode ctx 80000, page size 1, batch 16 and
32, it prints:

  HD prod|det   rep/hist/sep as the layer defines them, plus rep8 (distinct outputs over eight
                back-to-back calls on one input) and the worst diff in BF16 ulps
  HD addr       the previous call on a copy of input k at another address (same values): no
                value can be carried, only timing and L2 contents change
  HD flush      rep/hist/sep with a 256 MB L2 flush before every call
  HD ws         every workspace row, row sum and ticket, and the flat and cooperative
                counters, after every production call (the kernel's entry state)
  HD xplan      a call on each other plan (modes 11, 13, 1, 3, 51), the workspace scan after
                it, then the batch-16 call against its reference
  HD det_vs_prod  the deterministic merge against production (same math, other order)

det is attn_one.cu built with -DONE_DETM=1: per-warp partials in their own slots, summed by
the request's last CTA in split order. If merge order is the cause, det shows rep = hist =
sep = 0 while prod keeps them; a carry would survive in det too (the slots are never zeroed,
so a read before publication would read the previous call's partials).
"""

