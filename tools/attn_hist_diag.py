def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "muse_attention_decode/hist_diag.py"
    src = (ROOT / "muse_attention_decode/submission.py").read_text()
    cu = (ROOT / "muse_attention_decode/attn_one.cu").read_text()
    src, n = re.subn(r'_ONE_SRC = r""".*?"""', lambda _: f'_ONE_SRC = r"""\n{cu}"""', src,
                     flags=re.S)
    if n != 1:
        raise SystemExit("no _ONE_SRC block in submission.py")
    head = "# okc: problem=muse_attention_decode\n"
    if not src.startswith(head):
        raise SystemExit("submission.py does not start with the problem header")
    src = head + "# Input-history diagnostic (not a candidate).\n" + src[len(head):]
    out.write_text(src + DIAG)
    print("wrote", out)


if __name__ == "__main__":
    main()
