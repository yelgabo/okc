"""Write an attention-board check that measures the decode layer's two drifting T = 8 PDL edges in isolation.

    python3 tools/attn_make_pdl_bench.py PUBLIC.py LAYER.py OUT.py [--replays N] [--shapes all|t8]

The judged path of OUT.py is PUBLIC.py byte for byte (the public attention file); the runner is appended after
it and runs once at import. It builds the layer's own attention (ATT7_CUDA_SRC from LAYER.py with the layer's
_PDL8_EDITS applied: trigger at each segment's merge, __ldcg gate rows, programmatic attribute when pdl) together
with tools/attn_pdl_bench_extras.cu, and replays per shape and arm the chain

    producer (stands in for qkv sk2) -> attention (_launch7 lifted from LAYER.py) -> consumer (stands in for o sk2)
    -> audit (serialized; bumps the replay counter)

Arms: `attn` makes attention a PDL secondary of the producer, `o` makes the consumer a PDL secondary of attention,
`jit` keeps every edge serialized but runs a side-stream kernel that holds half the SMs for a jittered time while
attention starts (a staggered CTA start without PDL), `det` sets n_splits = nc = 8 so each FP32 workspace copy gets
exactly one split (an order-free merge), `F` alternates two qkv inputs by replay parity (a read of the previous
replay's or partly written qkv shows as a large error). The consumer compares attention's output against the
eager PDL-off output of the same parity per element; the audit compares what the consumer read with the final
output (an early read by the consumer, mechanism c).
"""

import ast
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

LAYER_NAMES = ["LOG2E", "SCRATCH_GUARD", "SCRATCH_SENTINEL", "_GUARDS", "_GUARDED_IDS", "_guarded", "_WS7",
               "_NUM_SMS7", "_workspace7", "_num_sms7", "_TUNED7", "OKC_FLATCOOP", "OKC_PDL", "OKC_FLAT1B",
               "OKC_PLAIN8", "OKC_F2", "OKC_S2", "OKC_W0_L1", "OKC_W0_PR", "OKC_W0_L8", "_plan7", "_CL7",
               "_cluster_bufs7", "_INV_FREQ_CACHE", "_inv_freq", "_launch7"]

EXTRA_CPP = """
int64_t pdlb_producer(int64_t w, int64_t wv_per_cta, int64_t src0, int64_t src1, int64_t qkv, int64_t n_vec,
                      int64_t ctr, int64_t fresh, int64_t trigger, int64_t sink, int64_t grid, int64_t smem,
                      int64_t stream);
int64_t pdlb_consumer(int64_t w, int64_t wv_per_cta, int64_t out, int64_t ref0, int64_t ref1, int64_t n_vec,
                      int64_t ctr, int64_t fresh, int64_t seen, int64_t cnt, int64_t maxulp, int64_t maxabs,
                      int64_t rep_nd, int64_t rep_ulp, int64_t nrep, int64_t sink, int64_t grid, int64_t pdl,
                      int64_t stream);
int64_t pdlb_audit(int64_t out, int64_t seen, int64_t n_vec, int64_t bad, int64_t ctr, int64_t stream);
int64_t pdlb_hog(int64_t ctr, int64_t base_ns, int64_t jitter_ns, int64_t sink, int64_t grid, int64_t smem,
                 int64_t stream);
"""

RUNNER = r'''

# Generated by tools/attn_make_pdl_bench.py: the layer's T = 8 PDL edges around its attention, measured at import.
import os as _pb_os
import time as _pb_time
import types as _pb_types

@@CONFIG@@

_PB_T0 = _pb_time.time()


def _pb_el():
    return f"t={_pb_time.time() - _PB_T0:.0f}s"


def _pb_build():
    import torch as _t
    from torch.utils.cpp_extension import load_inline as _li
    major, minor = _t.cuda.get_device_capability()
    _pb_os.environ["TORCH_CUDA_ARCH_LIST"] = f"{major}.{minor}" + ("a" if major == 9 else "")
    ext = _li(name="pdlb_att7_v1", cpp_sources=_PB_ATT7_CPP + _PB_EXTRA_CPP,
              cuda_sources=[_PB_ATT7_CUDA, _PB_EXTRA_CUDA],
              functions=["run", "pdlb_producer", "pdlb_consumer", "pdlb_audit", "pdlb_hog"],
              extra_cuda_cflags=["-DOKC_QDIRECT=0", "-DOKC_PK2=0", "-DOKC_W0ENABLE=1", "-O3",
                                 f"-DOKC_SM90={1 if major >= 9 else 0}", "--expt-relaxed-constexpr"],
              verbose=False)
    lay = _pb_types.ModuleType("pdlb_layer")
    lay.__dict__["torch"] = _t
    exec(compile(_PB_LAYER_PY, "layer_attention_launcher.py", "exec"), lay.__dict__)
    return ext, lay


def _pb_data(B, L, window, gen, dev, ctx=80000, spread=0.1):
    """The attention fields of the layer's _pdl8_data (same lengths, page table, cache layout)."""
    seq = (ctx * (1 + spread * (2 * torch.rand((B,), generator=gen, device=dev) - 1))).long().clamp_min(1)
    if B == 1:
        seq.fill_(ctx)
    max_pages = int(ctx * (1 + spread)) + 1 + L
    total = B * max_pages
    perm = torch.randperm(total, generator=gen, device=dev).to(torch.int32)
    pt = torch.full((B, max_pages), -1, dtype=torch.int32, device=dev)
    per = (seq + L).tolist()
    at = 0
    for b in range(B):
        pt[b, :per[b]] = perm[at:at + per[b]]
        at += per[b]
    pos = (seq[:, None] + torch.arange(L, device=dev)).view(B, L)
    loc = torch.gather(pt.long(), 1, pos).reshape(-1)
    kc = torch.empty((total, 1, 2, 64), dtype=torch.float8_e4m3fn, device=dev)
    vc = torch.empty_like(kc)
    for dst in (kc, vc):
        flat = dst.view(-1, 2, 64)
        for i in range(0, flat.shape[0], 1 << 20):
            n = min(1 << 20, flat.shape[0] - i)
            flat[i:i + n] = torch.randn((n, 2, 64), generator=gen, device=dev).to(torch.float8_e4m3fn)
    one = torch.ones((), dtype=torch.float32, device=dev)
    cfg = dict(batch=B, q_len=L, tokens=B * L, num_q_heads=16, num_kv_heads=2, head_dim=64, page_size=1,
               window=window, rope_theta=500000.0 if window else 0.0, qk_scale_factor=5.4730064863875,
               sm_scale=0.125, kv_scale=1.0)
    return {"config": cfg, "seq_lens": seq.to(torch.int32), "cache_loc": loc, "k_cache": kc, "v_cache": vc,
            "page_table": pt, "k_scale": one, "v_scale": one.clone()}


_PB_SUM = []


def _pb_shape(ext, lay, tag, B, L, window, seed):
    dev = torch.device("cuda")
    gen = torch.Generator(device=dev).manual_seed(seed)
    data = _pb_data(B, L, window, gen, dev)
    T = B * L
    src = [torch.randn((T, 2304), generator=gen, device=dev).to(torch.bfloat16) for _ in range(2)]
    qkv = torch.empty_like(src[0])
    owner = {"attention_scratch": {"rows": {}, "cluster": {}, "retained": []}}
    pf = torch.zeros(4 << 20, dtype=torch.uint8, device=dev)
    prefetch = (pf.data_ptr(), 4 << 20) if T in (1, 8) else (0, 0)
    wq = torch.randint(-2 ** 31, 2 ** 31 - 1, (2304 * 8192 // 2,), dtype=torch.int32, device=dev, generator=gen)
    wo = torch.randint(-2 ** 31, 2 ** 31 - 1, (8192 * 1024 // 2,), dtype=torch.int32, device=dev, generator=gen)
    wq_v = wq.numel() * 4 // 16 // _PB_PROD_GRID
    wo_v = min(_PB_CONS_BYTES // 16, wo.numel() * 4 // 16 // _PB_CONS_GRID)
    n_el = T * 1024
    n_vec = n_el // 8
    q_vec = T * 2304 // 8
    ctr = torch.zeros(1, dtype=torch.int32, device=dev)
    sink = torch.zeros(4, dtype=torch.int32, device=dev)
    cnt = torch.zeros(n_el, dtype=torch.int32, device=dev)
    mulp = torch.zeros_like(cnt)
    mabs = torch.zeros_like(cnt)
    rep_nd = torch.zeros(_PB_NREP, dtype=torch.int32, device=dev)
    rep_ulp = torch.zeros_like(rep_nd)
    bad = torch.zeros(1, dtype=torch.int32, device=dev)
    seen = torch.empty((T, 1024), dtype=torch.bfloat16, device=dev)
    det = dict(n_splits=8, nc=8, coop=1) if B == 1 else dict(n_splits=8, nc=8)

    def attention(pdl, override):
        d = dict(data, qkv=qkv)
        return lay._launch7(d, _mod=ext, pdl=pdl, attention_state=owner, prefetch=prefetch, **override)

    refs = {}
    for name, ov in (("plain", {}), ("det", det)):
        r = []
        for par in (0, 1):
            qkv.copy_(src[par])
            out = attention(False, ov)
            torch.cuda.synchronize()
            r.append(out.clone())
        refs[name] = r
    plan = lay._plan7(B, 1, L, window, data["page_table"].shape[1], 1, dev)
    print(f"PDLB {tag} plan {plan} tuned {lay._TUNED7.get((B, L, bool(window), 1))} det {det} "
          f"ref det-vs-plain max|diff| {float((refs['det'][0].float() - refs['plain'][0].float()).abs().max()):.3e} "
          f"{_pb_el()}", flush=True)
    side = torch.cuda.Stream()

    def chain(arm):
        attn_pdl, o_pdl, jit, fresh = "attn" in arm["edges"], "o" in arm["edges"], arm["jit"], arm["fresh"]
        r0, r1 = refs["det" if arm["det"] else "plain"]
        cur = torch.cuda.current_stream()
        rc = ext.pdlb_producer(wq.data_ptr(), wq_v, src[0].data_ptr(), src[1].data_ptr(), qkv.data_ptr(), q_vec,
                               ctr.data_ptr(), int(fresh), 1, sink.data_ptr(), _PB_PROD_GRID, _PB_PROD_SMEM,
                               cur.cuda_stream)
        if jit:
            side.wait_stream(cur)
            with torch.cuda.stream(side):
                rc |= ext.pdlb_hog(ctr.data_ptr(), _PB_HOG_NS, _PB_HOG_JIT, sink.data_ptr(), _PB_HOG_GRID,
                                   _PB_HOG_SMEM, side.cuda_stream)
        out = attention(attn_pdl, det if arm["det"] else {})
        if jit:
            cur.wait_stream(side)
        rc |= ext.pdlb_consumer(wo.data_ptr(), wo_v, out.data_ptr(), r0.data_ptr(), r1.data_ptr(), n_vec,
                                ctr.data_ptr(), int(fresh), seen.data_ptr(), cnt.data_ptr(), mulp.data_ptr(),
                                mabs.data_ptr(), rep_nd.data_ptr(), rep_ulp.data_ptr(), _PB_NREP, sink.data_ptr(),
                                _PB_CONS_GRID, int(o_pdl), cur.cuda_stream)
        rc |= ext.pdlb_audit(out.data_ptr(), seen.data_ptr(), n_vec, bad.data_ptr(), ctr.data_ptr(),
                             cur.cuda_stream)
        if rc:
            raise RuntimeError(f"launch error {rc}")
        return out

    refmax = float(refs["plain"][0].float().abs().max())
    for arm in _PB_ARMS:
        if _pb_time.time() - _PB_T0 > _PB_BUDGET_S:
            print(f"PDLB {tag} budget reached before {arm['name']}", flush=True)
            break
        name = arm["name"]
        try:
            for _ in range(3):
                chain(arm)
            torch.cuda.synchronize()
            g = torch.cuda.CUDAGraph()
            with torch.cuda.graph(g):
                chain(arm)
            torch.cuda.synchronize()
            for t in (ctr, cnt, mulp, mabs, rep_nd, rep_ulp, bad):
                t.zero_()
            torch.cuda.synchronize()
            for _ in range(_PB_REPLAYS):
                g.replay()
            torch.cuda.synchronize()
            c, mu, ma = cnt.cpu(), mulp.cpu(), mabs.view(torch.float32).cpu()
            rn = rep_nd[:_PB_REPLAYS].cpu()
            nb = int(bad.item())
            diff = (c > 0).nonzero().flatten().tolist()
            drift = float(ma.max()) / max(refmax, 1e-6)
            hist = [int(((mu >= lo) & (mu <= hi)).sum()) for lo, hi in ((1, 1), (2, 2), (3, 8), (9, 64), (65, 1 << 30))]
            rows = {}
            for i in diff:
                rows.setdefault((i // 1024, (i % 1024) // 64), []).append(i)
            rsz = sorted((len(v) for v in rows.values()), reverse=True)
            top = sorted(diff, key=lambda i: (-int(c[i]), -int(mu[i])))[:6]
            rb = refs["det" if arm["det"] else "plain"][0].flatten().float().cpu()
            tops = " ".join(f"[t{i // 1024} h{(i % 1024) // 64} d{i % 64} n={int(c[i])} ulp={int(mu[i])} "
                            f"ref={float(rb[i]):+.4g}]" for i in top)
            ts = []
            for _ in range(_PB_TIME_REPS):
                a = torch.cuda.Event(enable_timing=True)
                z = torch.cuda.Event(enable_timing=True)
                a.record()
                g.replay()
                z.record()
                ts.append((a, z))
            torch.cuda.synchronize()
            med = sorted(1000.0 * a.elapsed_time(z) for a, z in ts)[len(ts) // 2]
            line = (f"{tag} {name}: drift {drift:.3e} elements {len(diff)}/{c.numel()} replays_with_diff "
                    f"{int((rn > 0).sum())}/{_PB_REPLAYS} max_ulp {int(mu.max())} ulp_hist(1,2,3-8,9-64,>64) {hist} "
                    f"rows {len(rows)} row_sizes {rsz[:8]} audit_bad {nb} chain_us {med:.2f}")
            _PB_SUM.append(line)
            print(f"PDLB {line} top {tops} {_pb_el()}", flush=True)
            del g
        except Exception as exc:
            torch.cuda.synchronize()
            line = f"{tag} {name}: FAIL {type(exc).__name__}: {str(exc)[:300]}"
            _PB_SUM.append(line)
            print("PDLB " + line, flush=True)
    del data, src, qkv, owner, wq, wo, refs
    torch.cuda.synchronize()
    torch.cuda.empty_cache()


def _pb_main():
    try:
        ext, lay = _pb_build()
        print(f"PDLB built {_pb_el()}", flush=True)
    except Exception as exc:
        print(f"PDLB build FAIL {type(exc).__name__}: {str(exc)[:1500]}", flush=True)
        return
    for tag, B, L, window, seed in _PB_SHAPES:
        try:
            _pb_shape(ext, lay, tag, B, L, window, seed)
        except Exception as exc:
            print(f"PDLB {tag} FAIL {type(exc).__name__}: {str(exc)[:600]}", flush=True)
            torch.cuda.synchronize()
    print(f"PDLB done {_pb_el()}", flush=True)
    for line in _PB_SUM:
        print("PDLBSUM " + line, flush=True)


if not _pb_os.environ.get("PDLB_DONE"):
    _pb_os.environ["PDLB_DONE"] = "1"
    try:
        _pb_main()
    except Exception as _exc:
        print(f"PDLB failed: {type(_exc).__name__}: {_exc}", flush=True)
'''


def literal(src, name):
    tree = ast.parse(src)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in the layer file")


def layer_snippet(src):
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    found, parts = set(), []
    for node in tree.body:
        names = []
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names = [node.name]
        elif isinstance(node, ast.Assign):
            names = [getattr(t, "id", None) for t in node.targets]
        hit = [n for n in names if n in LAYER_NAMES]
        if hit:
            found.update(hit)
            parts.append("".join(lines[node.lineno - 1:node.end_lineno]))
    missing = set(LAYER_NAMES) - found
    if missing:
        raise SystemExit(f"layer file lacks {sorted(missing)}")
    return "\n".join(parts)


def arms(shapes):
    out = []
    for name, edges, jit, det, fresh in (
            ("off", (), 0, 0, 0), ("attn", ("attn",), 0, 0, 0), ("o", ("o",), 0, 0, 0),
            ("attn+o", ("attn", "o"), 0, 0, 0), ("jit", (), 1, 0, 0),
            ("det_off", (), 0, 1, 0), ("det_attn+o", ("attn", "o"), 0, 1, 0), ("det_jit", (), 1, 1, 0),
            ("F_off", (), 0, 0, 1), ("F_attn", ("attn",), 0, 0, 1), ("F_o", ("o",), 0, 0, 1),
            ("F_attn+o", ("attn", "o"), 0, 0, 1), ("F_det_attn+o", ("attn", "o"), 0, 1, 1)):
        out.append(dict(name=name, edges=edges, jit=jit, det=det, fresh=fresh))
    return out


def main():
    args = sys.argv[1:]
    if len(args) < 3:
        raise SystemExit(__doc__)
    pub_path, layer_path, out = Path(args.pop(0)), Path(args.pop(0)), Path(args.pop(0))
    replays, which = 2000, "all"
    while args:
        a = args.pop(0)
        if a == "--replays":
            replays = int(args.pop(0))
        elif a == "--shapes":
            which = args.pop(0)
        else:
            raise SystemExit(f"unknown option {a}")
    pub = pub_path.read_text()
    lsrc = layer_path.read_text()
    cuda = literal(lsrc, "ATT7_CUDA_SRC")
    for old, new, n in literal(lsrc, "_PDL8_EDITS")["ATT7_CUDA_SRC"]:
        if cuda.count(old) != n:
            raise SystemExit(f"PDL8 edit expected {n} matches, found {cuda.count(old)}: {old[:80]!r}")
        cuda = cuda.replace(old, new)
    extra = (ROOT / "tools/attn_pdl_bench_extras.cu").read_text()
    shapes = [("T8_full", 1, 8, 0, 801), ("T8_sliding", 1, 8, 2048, 802), ("T1_full", 1, 1, 0, 101),
              ("T1_sliding", 1, 1, 2048, 102), ("T16_sliding", 16, 1, 2048, 1602)]
    if which == "t8":
        shapes = shapes[:2]
    config = "\n".join([
        f"_PB_ATT7_CUDA = {cuda!r}",
        f"_PB_ATT7_CPP = {literal(lsrc, 'ATT7_CPP_SRC')!r}",
        f"_PB_EXTRA_CUDA = {extra!r}",
        f"_PB_EXTRA_CPP = {EXTRA_CPP!r}",
        f"_PB_LAYER_PY = {layer_snippet(lsrc)!r}",
        f"_PB_SHAPES = {shapes!r}",
        f"_PB_ARMS = {arms(shapes)!r}",
        f"_PB_REPLAYS = {replays!r}",
        "_PB_NREP = 4096",
        "_PB_TIME_REPS = 100",
        "_PB_BUDGET_S = 480.0",
        # qkv sk2 at M = 8 streams the 2304 x 8192 BF16 weight over the SMs; the o sk2 prefetches stages before its wait
        "_PB_PROD_GRID = 132",
        "_PB_PROD_SMEM = 81920",
        "_PB_CONS_GRID = 128",
        "_PB_CONS_BYTES = 65536",
        "_PB_HOG_GRID = 66",
        "_PB_HOG_SMEM = 200 * 1024",
        "_PB_HOG_NS = 2000",
        "_PB_HOG_JIT = 6000",
    ])
    text = pub + RUNNER.replace("@@CONFIG@@", config, 1)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    compile(text, str(out), "exec")
    print(f"wrote {out} sha256={hashlib.sha256(text.encode()).hexdigest()} "
          f"public sha256={hashlib.sha256(pub.encode()).hexdigest()} "
          f"layer sha256={hashlib.sha256(lsrc.encode()).hexdigest()} replays={replays} shapes={len(shapes)}")


if __name__ == "__main__":
    main()
