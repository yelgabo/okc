def _ob_stamps(vals):
    """Stamp deltas in microseconds from the first stamp (0 = not reached). stamp(k) writes
    dbg[1 + k]; dbg[0] holds the cooperative poll count and dbg[1] is never stamped."""
    base = vals[2]
